export const getLang = () => current;
export function setLang(id) {
  current = STR[id] ? id : "en";
  document.documentElement.lang = current;
}
// t("step", { n: "01" }) -> "Step 01". Values are inserted as given: escape them first if they are user data.
export function t(key, vars) {
  let s = STR[current][key] ?? STR.en[key] ?? key;
  if (vars && typeof s === "string") s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}
